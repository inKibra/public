// ============================================================================
// Standalone Discovery (for use outside Bun plugin context)
// ============================================================================

/**
 * Discover stories and return the manifest.
 * Use this for scripts, tests, or other contexts where the plugin isn't used.
 */
export async function getManifest(
  packageRoot: string = process.cwd(),
  configOverride?: StorybookConfig,
): Promise<{ manifest: StoryManifest; warnings: string[] }> {
  const result = await discoverStories(packageRoot, configOverride);
  return {
    manifest: result.manifest,
    warnings: result.warnings,
  };
}

/**
 * Generate the virtual module source for writing to disk.
 * Useful for pre-generating the manifest during build.
 */
export async function generateManifestModule(
  packageRoot: string = process.cwd(),
  configOverride?: StorybookConfig,
): Promise<string> {
  const result = await discoverStories(packageRoot, configOverride);
  return generateVirtualModule(result.manifest, result.files, packageRoot);
}
